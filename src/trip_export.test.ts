import { describe, expect, it } from 'vitest';
import { formatTripMarkdown } from './trip_export';
import type { BoardPin } from './board_store';

const PIN = (placeName: string, city: string, sourceHost: string, addedAt: number): BoardPin => ({
  place: {
    identified: true,
    placeName,
    city,
    country: 'Greece',
    confidence: 0.9,
    oneLiner: 'Blue domes.',
  },
  sourceHost,
  addedAt,
});

describe('trip_export', () => {
  it('renders the golden sample with places, route, and itinerary', () => {
    const pins = [PIN('Oia', 'Oia', 'example.com', 1), PIN('Fira', 'Fira', 'blog.example', 2)];

    expect(formatTripMarkdown({ pins, itinerary: '## Day 1\n\nWander Oia.' }))
      .toBe(`# Trip board export

Exported 2 places.

## Places

1. **Oia, Greece** - found on example.com
   [Maps](https://www.google.com/maps/search/?api=1&query=Oia%2C%20Greece) · [Hotels](https://www.google.com/travel/hotels?q=Oia%2C%20Greece&hl=en)
2. **Fira, Greece** - found on blog.example
   [Maps](https://www.google.com/maps/search/?api=1&query=Fira%2C%20Greece) · [Hotels](https://www.google.com/travel/hotels?q=Fira%2C%20Greece&hl=en)

## Route

[Open the route in Google Maps](https://www.google.com/maps/dir/?api=1&origin=Oia%2C%20Greece&destination=Fira%2C%20Greece)

## Itinerary (AI-generated)

## Day 1

Wander Oia.

---

*Places and links come from your saved board; any itinerary above was generated by an AI provider and may contain mistakes.*
`);
  });

  it('escapes markdown in names and hosts and keeps paren links working', () => {
    const pins = [
      PIN('Oia [old *town*] (Santorini)', 'Oia_town', 'exa`mple.com | photos', 1),
      PIN('Fira', 'Fira', 'blog.example', 2),
    ];

    const out = formatTripMarkdown({ pins });

    expect(out).toContain(
      '1. **Oia \\[old \\*town\\*\\] \\(Santorini\\), Oia\\_town, Greece** - found on exa\\`mple.com \\| photos'
    );
    expect(out).toContain(
      '[Maps](https://www.google.com/maps/search/?api=1&query=Oia%20%5Bold%20*town*%5D%20%28Santorini%29%2C%20Oia_town%2C%20Greece)'
    );
    expect(out).toContain(
      '&origin=Oia%20%5Bold%20*town*%5D%20%28Santorini%29%2C%20Oia_town%2C%20Greece&destination=Fira%2C%20Greece'
    );
    expect(out).toContain('No itinerary generated yet.');
  });

  it('omits the route for a single pin and marks stale itineraries', () => {
    const pins = [PIN('Oia', 'Oia', 'example.com', 1)];

    const single = formatTripMarkdown({ pins });
    expect(single).not.toContain('## Route');
    expect(single).toContain('Exported 1 place.');

    const stale = formatTripMarkdown({ pins, itinerary: '## Day 1', itineraryStale: true });
    expect(stale).toContain('## Itinerary (AI-generated) (outdated - the board changed since)');
  });
});
