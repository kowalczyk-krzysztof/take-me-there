import type { BoardPin } from './board_store';
import { buildDestination, buildLinks, mapsDirUrl } from './deep_links';

export interface TripExportInput {
  pins: BoardPin[];
  itinerary?: string;
  itineraryStale?: boolean;
}

export const TRIP_EXPORT_FILENAME = 'take-me-there-trip.md';

const escapeMarkdown = (text: string): string =>
  text
    .replace(/[\0-\x1F\x7F]+/g, ' ')
    .replace(/[\\`*_{}[\]()#+!|<>~]/g, '\\$&')
    .replace(/\s+/g, ' ')
    .trim();

const encodeHref = (href: string): string => href.replace(/\(/g, '%28').replace(/\)/g, '%29');

const LINK_LABELS: Record<string, string> = {
  maps: 'Maps',
  flights: 'Flights',
  hotels: 'Hotels',
  airbnb: 'Airbnb',
  booking: 'Booking',
  getyourguide: 'GetYourGuide',
  tripadvisor: 'TripAdvisor',
  expedia: 'Expedia',
};

export const formatTripMarkdown = (input: TripExportInput): string => {
  const lines: string[] = [`# Trip board export`, ''];

  const names = input.pins.map((pin) =>
    buildDestination(pin.place.placeName, pin.place.city, pin.place.country)
  );
  lines.push(`Exported ${names.length} ${names.length === 1 ? 'place' : 'places'}.`, '');

  lines.push('## Places', '');
  input.pins.forEach((pin, index) => {
    const name = escapeMarkdown(names[index]);
    const host = escapeMarkdown(pin.sourceHost || 'unknown source');
    lines.push(`${index + 1}. **${name}** - found on ${host}`);

    const links = buildLinks(names[index])
      .map((link) => `[${LINK_LABELS[link.id] ?? link.id}](${encodeHref(link.href)})`)
      .join(' · ');

    if (links) {
      lines.push(`   ${links}`);
    }
  });
  lines.push('');

  const routeUrl = mapsDirUrl(names);

  if (routeUrl) {
    lines.push('## Route', '', `[Open the route in Google Maps](${encodeHref(routeUrl)})`, '');
  }

  if (input.itinerary) {
    const stale = input.itineraryStale === true ? ' (outdated - the board changed since)' : '';
    lines.push(`## Itinerary (AI-generated)${stale}`, '', input.itinerary.trim(), '');
  } else {
    lines.push('## Itinerary', '', 'No itinerary generated yet.', '');
  }

  lines.push(
    '---',
    '',
    '*Places and links come from your saved board; any itinerary above was generated by an AI provider and may contain mistakes.*',
    ''
  );

  return lines.join('\n');
};
